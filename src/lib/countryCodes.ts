/** Résout le pays et le drapeau à partir d'un code pays de source de données. */
export function resolveCountryCode(rawCode: string): CountryDisplay | undefined {
  const code = rawCode.trim().toUpperCase();
  if (!code) return undefined;
  const canonical = COUNTRY_CODE_ALIASES[code] ?? code;
  return COUNTRIES_BY_CODE[canonical];
}
